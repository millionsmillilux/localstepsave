export function getJobById(id: string, extra: Job[] = []): Job | undefined {
  return [...extra, ...demoJobs].find((job) => job.id === id);
}

export function formatPay(job: Pick<Job, "payMin" | "payMax" | "payNote">): string {
  if (job.payMin === null) return job.payNote ?? "Unpaid";
  const range = job.payMin === job.payMax ? `$${job.payMin}/hr` : `$${job.payMin}–${job.payMax}/hr`;
  return job.payNote ? `${range} · ${job.payNote}` : range;
}

